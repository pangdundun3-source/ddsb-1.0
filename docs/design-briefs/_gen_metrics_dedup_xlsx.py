def main():
    wb = Workbook()
    ws = wb.active
    ws.title = "去重指标"

    ws["A1"] = "统计指标去重口径（开发/测试）— 一指标一行"
    ws["A1"].font = TITLE_FONT
    ws.merge_cells("A1:H1")
    ws["A2"] = (
        "来源：产品指标表去重。同义名合并为一行。"
        "「出现位置」仅说明原先散落模块，实现与验收以本表公式为准。"
        "版本：2026-11-15"
    )
    ws["A2"].alignment = WRAP
    ws.merge_cells("A2:H2")
    ws.row_dimensions[2].height = 36

    for i, h in enumerate(HEADERS, 1):
        cell = ws.cell(4, i, h)
        cell.fill = HEADER_FILL
        cell.font = HEADER_FONT
        cell.alignment = Alignment(wrap_text=True, vertical="center", horizontal="center")
        cell.border = THIN
    ws.freeze_panes = "A5"
    ws.auto_filter.ref = f"A4:H4"

    for r_idx, row in enumerate(ROWS, 5):
        for c_idx, val in enumerate(row, 1):
            cell = ws.cell(r_idx, c_idx, val)
            cell.alignment = WRAP
            cell.border = THIN
            if r_idx % 2 == 0:
                cell.fill = ALT
        ws.row_dimensions[r_idx].height = 55

    widths = [14, 22, 36, 10, 32, 22, 40, 48]
    for i, w in enumerate(widths, 1):
        ws.column_dimensions[get_column_letter(i)].width = w
    ws.row_dimensions[4].height = 28

    # 说明 sheet
    ws2 = wb.create_sheet("去重说明")
    notes = [
        ["去重规则", "同一算法只保留一行；页面文案不同写入「同义/别名」"],
        ["合并示例", "累计上报=累计报送=累计报送量；首审直通率=直通率；被驳回待修改≈已驳回待重报（状态同，范围可加「可改报」）"],
        ["不合并", "通过处理(审核动作) ≠ 累计采纳量(终态)；驳回处理(审核动作) ≠ 被驳回/驳回整改量(报送状态)"],
        ["时间字段", "报送时间 submitTime；到达时间 arrivedAt；办结时间 auditTime — 禁止混用"],
        ["除零", "凡率类分母为 0，显示 --"],
        ["配套", "详见同目录 统计指标算法口径-开发测试.md"],
    ]
    ws2["A1"] = "说明"
    ws2["A1"].font = TITLE_FONT
    for i, (k, v) in enumerate(notes, 3):
        ws2.cell(i, 1, k).font = Font(bold=True)
        ws2.cell(i, 2, v).alignment = WRAP
        ws2.row_dimensions[i].height = 30
    ws2.column_dimensions["A"].width = 14
    ws2.column_dimensions["B"].width = 80

    wb.save(OUT)
    print(f"Wrote {OUT} rows={len(ROWS)}")


if __name__ == "__main__":
    main()
