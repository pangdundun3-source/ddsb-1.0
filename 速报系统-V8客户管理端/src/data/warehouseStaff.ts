const phoneOf = (index: number) => {
  const prefixes = ['138', '139', '137', '136', '135', '158', '159', '186', '187', '188'];
  const rest = String(10000000 + ((index * 7919) % 90000000)).padStart(8, '0');
  return `${prefixes[index % prefixes.length]}${rest}`;
};

export const WAREHOUSE_STAFF: WarehouseStaff[] = NAMED_STAFF.map(([name, nickname, phone], index) => ({
  id: `staff-${index + 1}`,
  name,
  nickname,
  phone: phone || phoneOf(index + 1)
}));

export const resolveWarehouseStaff = (idOrName: string) =>
  WAREHOUSE_STAFF.find((item) => item.id === idOrName || item.name === idOrName);

